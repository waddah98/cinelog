// Small helper: find one movie by its id.
// Returns undefined when no movie has that id (for example, a wrong URL).
export function getMovieById(movieId) {
  return movies.find((movie) => movie.id === movieId);
}

// Small helper: build a list of every genre used in the catalog, sorted A–Z.
// The Explore page uses it to fill the genre filter.
export function getAllGenres() {
  const genres = [];

  movies.forEach((movie) => {
    movie.genres.forEach((genre) => {
      if (!genres.includes(genre)) {
        genres.push(genre);
      }
    });
  });

  genres.sort();
  return genres;
}
